"""Generate deterministic LVGL assets from editable SVG artwork."""
from pathlib import Path
from io import BytesIO
import struct
import resvg_py
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
OUT = ROOT / "main" / "generated"
OUT.mkdir(exist_ok=True)


def raster(svg: str, width: int, height: int) -> Image.Image:
    png = resvg_py.svg_to_bytes(svg_string=svg, width=width * 4, height=height * 4)
    return Image.open(BytesIO(png)).convert("RGBA").resize((width, height), Image.Resampling.LANCZOS)


def emit(name: str, image: Image.Image, alpha: bool) -> None:
    if alpha:
        data = image.tobytes("raw", "BGRA")
        fmt = "LV_COLOR_FORMAT_ARGB8888"
        stride = image.width * 4
    else:
        data = b"".join(struct.pack("<H", ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
                        for r, g, b, _ in image.get_flattened_data())
        fmt = "LV_COLOR_FORMAT_RGB565"
        stride = image.width * 2
    lines = [", ".join(f"0x{b:02x}" for b in data[i:i + 24]) for i in range(0, len(data), 24)]
    code = f'''// Generated by tools/generate_assets.py. Do not edit.
#include "lvgl.h"
static const uint8_t {name}_pixels[] __attribute__((aligned(4))) = {{
''' + ",\n".join(lines) + f'''
}};
const lv_image_dsc_t {name} = {{
    .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = {fmt},
                 .flags = 0, .w = {image.width}, .h = {image.height}, .stride = {stride} }},
    .data_size = sizeof({name}_pixels), .data = {name}_pixels,
}};
'''
    (OUT / f"{name}.c").write_text(code)
    image.save(ASSETS / f"{name}.png")


# SVGs are the editable master artwork; generation never rewrites them.
artwork = {
    "clock_dial": ("dial.svg", 368, 448, False),
    "clock_hour": ("clock_hour.svg", 32, 136, True),
    "clock_minute": ("clock_minute.svg", 24, 182, True),
    "clock_second": ("clock_second.svg", 36, 224, True),
}
for name, (filename, width, height, alpha) in artwork.items():
    svg = (ASSETS / filename).read_text()
    emit(name, raster(svg, width, height), alpha)

# A full-size composed reference image for review, not used as firmware animation.
preview = Image.open(ASSETS / "clock_dial.png").convert("RGBA")
for name, pivot, angle in [("clock_hour", (16,112), 305), ("clock_minute", (12,158), 60), ("clock_second", (18,166), 248)]:
    hand = Image.open(ASSETS / f"{name}.png")
    layer = Image.new("RGBA", (368*4,448*4))
    hand = hand.resize((hand.width*4,hand.height*4),Image.Resampling.LANCZOS)
    layer.alpha_composite(hand, ((184-pivot[0])*4,(224-pivot[1])*4))
    layer = layer.rotate(-angle, Image.Resampling.BICUBIC, center=(184*4,224*4))
    preview.alpha_composite(layer.resize((368,448),Image.Resampling.LANCZOS))
preview.save(ROOT / "clock-preview.png")
print("Generated dial and three antialiased hand assets, plus clock-preview.png")
