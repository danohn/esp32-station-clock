"""Generate compact firmware transitions and setup locations from pinned IANA tzdata.

Run with uv run tools/generate_timezones.py [--check]. No host timezone data is used.
"""
import argparse
from datetime import datetime, timezone
from importlib.resources import files
import json
from pathlib import Path
import struct
import tzdata
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parents[1]
START = int(datetime(2024, 1, 1, tzinfo=timezone.utc).timestamp())
END = int(datetime(2100, 1, 1, tzinfo=timezone.utc).timestamp())
DATA = files('tzdata.zoneinfo')


def explicit_transitions(raw):
    """Read transition instants from the 64-bit section of a TZif v2/v3 file."""
    def header(at):
        assert raw[at:at + 4] == b'TZif'
        return struct.unpack('>6I', raw[at + 20:at + 44])
    ut, std, leap, count, types, chars = header(0)
    at = 44 + count * 5 + types * 6 + chars + leap * 8 + std + ut
    _, _, _, count, _, _ = header(at)
    return struct.unpack_from(f'>{count}q', raw, at + 44)


def transitions(raw):
    from io import BytesIO
    zone = ZoneInfo.from_file(BytesIO(raw))
    def offset(epoch):
        return int(datetime.fromtimestamp(epoch, timezone.utc).astimezone(zone).utcoffset().total_seconds())
    result = [(0, offset(START))]
    explicit = explicit_transitions(raw)
    for epoch in explicit:
        if START < epoch < END and offset(epoch) != result[-1][1]:
            result.append((epoch - START, offset(epoch)))
    # TZif has exact instants for irregular rules (e.g. Ramadan). Past its last
    # explicit instant, zoneinfo expands the file's recurring POSIX footer.
    # Those annual future rules have transitions more than a day apart.
    cursor = max(START, explicit[-1] if explicit else START)
    before = offset(cursor)
    while cursor < END - 1:
        following = min(cursor + 86400, END - 1)
        after = offset(following)
        if before != after:
            low, high = cursor, following
            while high - low > 1:
                middle = (low + high) // 2
                if offset(middle) == before: low = middle
                else: high = middle
            result.append((high - START, after))
        cursor, before = following, after
    return tuple(result)


def generate():
    ids = sorted(files('tzdata').joinpath('zones').read_text().splitlines())
    countries = dict(line.split('\t', 1) for line in DATA.joinpath('iso3166.tab').read_text().splitlines() if line and not line.startswith('#'))
    locations = {}
    for line in DATA.joinpath('zone.tab').read_text().splitlines():
        if line and not line.startswith('#'):
            code, _, name, *_ = line.split('\t')
            city = name.split('/')[-1].replace('_', ' ')
            region = name.split('/')[0]
            locations[name] = f'{city} — {countries[code]} ({region})'
    locations['UTC'] = 'UTC — Coordinated Universal Time'
    # All IANA aliases are accepted, even though the picker shows geographical
    # locations rather than obsolete names or confusing Etc/GMT sign offsets.
    links = {}
    for line in DATA.joinpath('tzdata.zi').read_text().splitlines():
        if line.startswith('L '):
            _, target, alias = line.split()
            links[alias] = target
    def canonical(name):
        while name in links: name = links[name]
        return name
    visible_by_canonical = {canonical(name): name for name in sorted(locations)}
    aliases = {name: name if name in locations else visible_by_canonical.get(canonical(name), name) for name in ids}
    aliases.update({'Sydney': 'Australia/Sydney', 'Berlin': 'Europe/Berlin', 'UTC': 'UTC'})
    metadata = {'version': tzdata.IANA_VERSION, 'startYear': 2024, 'endYear': 2100,
                'locations': [{'id': name, 'label': label} for name, label in sorted(locations.items(), key=lambda item: item[1])],
                'aliases': aliases}
    sequences, flattened, records, cache = {}, [], [], {}
    for name in ids:
        raw = DATA.joinpath(name).read_bytes()
        if raw not in cache: cache[raw] = transitions(raw)
        sequence = cache[raw]
        if sequence not in sequences:
            sequences[sequence] = len(flattened)
            flattened.extend(sequence)
        records.append(f'    {{"{name}", {sequences[sequence]}, {len(sequence)}}},')
    header = '// Generated by tools/generate_timezones.py; IANA ' + tzdata.IANA_VERSION + '. Do not edit.\n#pragma once\n#include <cstdint>\nnamespace clock_zone::data {\n'
    header += f'inline constexpr char version[] = "{tzdata.IANA_VERSION}";\ninline constexpr int64_t start = {START}LL, end = {END}LL;\n'
    header += 'struct Transition { uint32_t since; int32_t offset; };\nstruct Zone { const char *id; uint32_t first; uint16_t count; };\n'
    header += 'inline constexpr Transition transitions[] = {\n' + ''.join(f'    {{{since}U, {offset}}},\n' for since, offset in flattened) + '};\n'
    header += 'inline constexpr Zone zones[] = {\n' + '\n'.join(records) + '\n};\n}\n'
    encoded = json.dumps(metadata, ensure_ascii=False, indent=2) + '\n'
    return {ROOT / 'main/generated/timezone_catalog.hpp': header,
            ROOT / 'assets/timezones.json': encoded,
            ROOT / 'site/timezones.js': '// Generated by tools/generate_timezones.py; do not edit.\nexport const timezoneCatalog = ' + encoded.rstrip() + ';\n'}, len(ids), len(flattened)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs, count, transitions_count = generate()
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content: stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale: raise SystemExit('Regenerate timezone data: ' + ', '.join(stale))
    print(f'IANA {tzdata.IANA_VERSION}: {count} IDs, {transitions_count} shared transitions, 2024–2099' + (' verified' if args.check else ' generated'))


if __name__ == '__main__': main()
